from __future__ import annotations

import json
import os
import sys

import numpy as np
from Bio import Align

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = HERE
while not os.path.isdir(os.path.join(ROOT, 'src')) and os.path.dirname(ROOT) != ROOT:
    ROOT = os.path.dirname(ROOT)
sys.path.insert(0, os.path.join(ROOT, 'src'))

import data_loader as dl

BENCH = ['TE18', 'TL12', 'JL10', 'RB9']
MIN_LEN_RATIO = 0.8
OUT_JSON = os.path.join(ROOT, 'results', 'overlap_census.json')
OUT_MD = os.path.join(ROOT, 'docs', 'tables', 'dataset_overlap_census.md')

aligner = Align.PairwiseAligner()
aligner.mode = 'global'
aligner.match_score = 1.0
aligner.mismatch_score = -1.0
aligner.open_gap_score = -4.0
aligner.extend_gap_score = -1.0


def identity(a, b):
    
    if min(len(a), len(b)) / max(len(a), len(b)) < MIN_LEN_RATIO:
        return 0.0
    aln = aligner.align(a, b)[0]
    matches = sum(1 for (x, y) in zip(*aln) if x == y and x != '-')
    return matches / min(len(a), len(b))


def max_identity_against(seq, ref_seqs):
    best, best_id = 0.0, None
    for rid, s in ref_seqs:
        v = identity(seq, s)
        if v > best:
            best, best_id = v, rid
    return best, best_id


def main():
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass
    data = dl.load_all()
    train = [(s['rna_id'], s['sequence']) for s in data['train']]
    val = [(s['rna_id'], s['sequence']) for s in data['val']]
    train_seq = {s for _, s in train}
    val_seq = {s for _, s in val}
    print(f'Reference sets: {len(train)} training · {len(val)} validation chains')

    rows = {}
    for b in BENCH:
        chains = [(s['rna_id'], s['sequence']) for s in data[b]]
        rec = {'n_chains': len(chains), 'exact_train': [], 'exact_val': [],
               'hom80_train': [], 'hom80_val': [], 'hom70_train': []}
        for rid, seq in chains:
            if seq in train_seq:
                rec['exact_train'].append(rid)
            if seq in val_seq:
                rec['exact_val'].append(rid)
            t80, _ = max_identity_against(seq, train)
            v80, _ = max_identity_against(seq, val)
            if t80 >= 0.8:
                rec['hom80_train'].append(rid)
            if v80 >= 0.8:
                rec['hom80_val'].append(rid)
            if t80 >= 0.7:
                rec['hom70_train'].append(rid)
        rec['n_exact_train'] = len(rec['exact_train'])
        rec['n_exact_val'] = len(rec['exact_val'])
        rec['n_exact_any'] = len(set(rec['exact_train']) | set(rec['exact_val']))
        rec['n_hom80_train'] = len(rec['hom80_train'])
        rec['n_hom80_val'] = len(rec['hom80_val'])
        rec['n_hom80_any'] = len(set(rec['hom80_train']) | set(rec['hom80_val']))
        rec['n_hom70_train'] = len(rec['hom70_train'])
        rows[b] = rec
        print(f'  {b:<5} n={rec["n_chains"]:>3}  identical: train {rec["n_exact_train"]:>2} / '
              f'val {rec["n_exact_val"]}  ≥80%: train {rec["n_hom80_train"]:>2} / '
              f'val {rec["n_hom80_val"]}  ≥70%(train) {rec["n_hom70_train"]}')

    total = {k: sum(rows[b][k] for b in BENCH) for k in
             ['n_chains', 'n_exact_train', 'n_exact_val', 'n_hom80_train', 'n_hom80_val',
              'n_hom70_train']}
    total['n_exact_any'] = sum(rows[b]['n_exact_any'] for b in BENCH)
    total['n_hom80_any'] = sum(rows[b]['n_hom80_any'] for b in BENCH)
    json.dump({'criterion': f'exact sequence match; homology = max identity (global alignment, '
                            f'length ratio >= {MIN_LEN_RATIO})',
               'per_benchmark': rows, 'total': total,
               'reference_sizes': {'train': len(train), 'val': len(val)}},
              open(OUT_JSON, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

    L = ['# Overlap of each test set with the training/validation sets', '',
         '> Generated by `python scripts/21_overlap_census.py` '
         '(values in `results/overlap_census.json`)',
         f'> Reference sets: {len(train)} training · {len(val)} validation chains. '
         'Homology = maximum identity from a global alignment, restricted to chain pairs '
         'with a length ratio ≥ 0.8.', '',
         '| Test set | Chains | Identical to **training** | Identical to **validation** '
         '| Total (deduplicated) | ≥80% to training | ≥80% to validation | Combined ≥80% |',
         '|:---|---:|---:|---:|---:|---:|---:|---:|']
    for b in BENCH:
        r = rows[b]
        L.append(f'| {b} | {r["n_chains"]} | {r["n_exact_train"]} | {r["n_exact_val"]} '
                 f'| **{r["n_exact_any"]}** | {r["n_hom80_train"]} | {r["n_hom80_val"]} '
                 f'| **{r["n_hom80_any"]}** |')
    L.append(f'| **Total** | **{total["n_chains"]}** | **{total["n_exact_train"]}** '
             f'| **{total["n_exact_val"]}** | **{total["n_exact_any"]}** '
             f'| **{total["n_hom80_train"]}** | **{total["n_hom80_val"]}** '
             f'| **{total["n_hom80_any"]}** |')
    L += ['', '> The "Total" column is deduplicated over **test chains**: a test chain that matches '
          'both a training and a validation chain is counted only once.', '',
          '## Details: which chains overlap', '']
    for b in BENCH:
        r = rows[b]
        L += [f'**{b}** ({r["n_chains"]} chains, of which {r["n_hom80_any"]} are homologous to '
              'the training/validation sets)', '',
              f'- Identical to a training chain ({r["n_exact_train"]}): '
              f'{", ".join(r["exact_train"]) or "none"}',
              f'- Identical to a validation chain ({r["n_exact_val"]}): '
              f'{", ".join(r["exact_val"]) or "none"}',
              f'- ≥80% identity to a training chain but not fully identical '
              f'({r["n_hom80_train"] - r["n_exact_train"]}): '
              f'{", ".join(sorted(set(r["hom80_train"]) - set(r["exact_train"]))) or "none"}', '']
    os.makedirs(os.path.dirname(OUT_MD), exist_ok=True)
    open(OUT_MD, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'\n[written] {OUT_JSON}\n[written] {OUT_MD}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
