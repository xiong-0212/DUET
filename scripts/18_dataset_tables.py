from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = HERE

while not os.path.isdir(os.path.join(ROOT, 'src')) and os.path.dirname(ROOT) != ROOT:
    ROOT = os.path.dirname(ROOT)
sys.path.insert(0, os.path.join(ROOT, 'src'))

import data_loader as dl

SRC = {'train': 'HARIBOSS + TR60', 'val': 'HARIBOSS + TR60', 'TE18': 'RNAsite',
       'TL12': 'ZeSTa', 'JL10': 'ZeSTa', 'RB9': 'RBind (RB19)'}
NAME = {'train': 'Training', 'val': 'Validation', 'TE18': 'TE18', 'TL12': 'TL12',
        'JL10': 'JL10', 'RB9': 'RB9'}
SPLITS = ['train', 'val', 'TE18', 'TL12', 'JL10', 'RB9']


def stats(samples):
    n_nt = sum(len(s['sequence']) for s in samples)
    pos = sum(sum(s['labels']) for s in samples)
    return {'chains': len(samples), 'nucleotides': n_nt, 'positive': pos,
            'negative': n_nt - pos, 'positive_ratio': pos / n_nt if n_nt else 0.0,
            'ratio': (n_nt - pos) / pos if pos else 0.0}


def raw_rb9():
    
    path = os.path.join(dl.COBRA_DIR, dl.TEST_SETS['RB9'])
    recs = dl.parse_bindingsite(path)
    out = []
    for rid, rec in recs.items():
        if len(rec['seq']) > dl.MAX_LEN:
            continue
        out.append(dl.sample_from(rid, rec, 'RB9'))
    return out


def remove_ids():
    leak = json.load(open(os.path.join(ROOT, 'data', 'leaked_pairs.json'), encoding='utf-8'))
    return set(leak['remove_train_ids']), set(leak['remove_val_ids'])


def main():
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass

    data = dl.load_all()
    rm_tr, rm_val = remove_ids()
    dedup = set(dl.DROP_FROM_SPLIT.get('RB9', []))

    before, after = {}, {}
    for split in SPLITS:
        if split == 'RB9':
            raw = raw_rb9()
            before[split] = stats(raw)
            after[split] = stats([s for s in raw if s['rna_id'] not in dedup])
        else:
            drop = rm_tr if split == 'train' else (rm_val if split == 'val' else set())
            before[split] = stats(data[split])
            after[split] = stats([s for s in data[split] if s['rna_id'] not in drop])

    json.dump({'before': before, 'after': after}, open(os.path.join(ROOT, 'results',
              'dataset_tables.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

    HEAD = ('| Dataset | Source | Chains | Nucleotides | Positive sites | Negative sites '
            '| Positive ratio | Ratio (neg : pos) |')
    ALIGN = '|:---|:---|---:|---:|---:|---:|---:|---:|'

    def rows(tab):
        out = []
        for split in SPLITS:
            s = tab[split]
            out.append(f'| {NAME[split]} | {SRC[split]} | {s["chains"]} | {s["nucleotides"]:,} '
                       f'| {s["positive"]:,} | {s["negative"]:,} | {s["positive_ratio"]:.3f} '
                       f'| {s["ratio"]:.2f} : 1 |')
        return out

    md = ['# Dataset statistics: before / after cleaning (columns match Table 1 of the paper)', '',
          '> Generated by `python scripts/18_dataset_tables.py` (values are also written to '
          '`results/dataset_tables.json`)',
          '> "Cleaning" = de-leaking (dropping training/validation chains identical to a test '
          'sequence) + test-set deduplication (the 3 RB9 chains duplicated in TE18)',
          '', '## Before cleaning (original split of the release)', '', HEAD, ALIGN] + rows(before) + [
          '', '## After cleaning (protocol used throughout the paper)', '', HEAD, ALIGN] + rows(after) + [
          '', '> Training: 345 → 314 (31 chains identical to a test sequence removed);',
          '> Validation: 43 → 40 (3 chains removed);',
          '> RB9: 9 → 6 (1nem_A / 1q8n_A / 2tob_A removed; they are kept in TE18);',
          '> TE18 / TL12 / JL10 unchanged. A positive site is a nucleotide with a heavy atom '
          'within 4 Å of a ligand heavy atom.', '']
    md_path = os.path.join(ROOT, 'docs', 'tables', 'dataset_statistics_before_after_cleaning.md')
    os.makedirs(os.path.dirname(md_path), exist_ok=True)
    open(md_path, 'w', encoding='utf-8').write('\n'.join(md))


    tex = [r'% Supplementary table: the published split before de-leaking. Generated by',
           r'% scripts/18_dataset_tables.py — the column layout matches Table 1 of the paper.',
           r'\begin{table}[htbp]', r'\centering', r'\footnotesize',
           r'\setlength{\tabcolsep}{4pt}',
           r'\caption{The four benchmarks \emph{before} de-leaking, i.e.\ as distributed with the',
           r'training set and the test sets of the original release. The columns are identical to',
           r'those of Table~1 of the main text, which reports the same quantities after de-leaking.',
           r'Binding nucleotides are the minority class in every split.',
           r'The three RB9 chains that also occur in TE18 are still counted here.}',
           r'\label{tab:data-before}',
           r'\begin{tabular}{l l r r r r r r}', r'\toprule',
           r'Dataset & Source & Chains & Nucleo- & Positive & Negative & Positive & Ratio \\',
           r'        &        &        & tides   & sites    & sites    & ratio    & (neg : pos) \\',
           r'\midrule']
    for split in SPLITS:
        s = before[split]
        tex.append(f'{NAME[split]:<10} & {SRC[split]} & {s["chains"]} & {s["nucleotides"]:,} '
                   f'& {s["positive"]:,} & {s["negative"]:,} & {s["positive_ratio"]:.3f} '
                   f'& {s["ratio"]:.2f} : 1 \\\\')
    tex += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    tex_path = os.path.join(ROOT, 'paper', 'tables_before_cleaning.tex')
    open(tex_path, 'w', encoding='utf-8').write('\n'.join(tex))

    for tag, tab in (('before cleaning', before), ('after cleaning', after)):
        print(tag)
        for split in SPLITS:
            s = tab[split]
            print(f'  {NAME[split]:<11}{s["chains"]:>4} chains  {s["nucleotides"]:>7,} nt  '
                  f'pos {s["positive"]:>5,}  neg {s["negative"]:>6,}  '
                  f'{s["positive_ratio"]:.3f}  {s["ratio"]:.2f}:1')
    print(f'\n[written] {md_path}')
    print(f'[written] {tex_path}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
